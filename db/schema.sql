CREATE TABLE IF NOT EXISTS orders (
  id SERIAL PRIMARY KEY, reference VARCHAR(64) UNIQUE NOT NULL, token_hash VARCHAR(64) NOT NULL,
  full_name VARCHAR(128) NOT NULL, birthdate DATE NULL, contact VARCHAR(128) NOT NULL,
  sign_id VARCHAR(32) NOT NULL, status VARCHAR(32) NOT NULL DEFAULT 'created',
  created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
  expires_at TIMESTAMP WITH TIME ZONE DEFAULT (CURRENT_TIMESTAMP + INTERVAL '12 months'));
CREATE TABLE IF NOT EXISTS payments (
  id SERIAL PRIMARY KEY, order_id INTEGER REFERENCES orders(id) ON DELETE CASCADE,
  provider VARCHAR(32) NOT NULL, transaction_id VARCHAR(128) UNIQUE NOT NULL,
  amount NUMERIC(12, 2) NOT NULL, currency VARCHAR(8) NOT NULL DEFAULT 'XOF',
  status VARCHAR(32) NOT NULL, raw_payload JSONB, created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP);
CREATE TABLE IF NOT EXISTS webhook_events (
  id SERIAL PRIMARY KEY, provider VARCHAR(32) NOT NULL, event_id VARCHAR(128) UNIQUE NOT NULL,
  payload JSONB, processed_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP);
CREATE TABLE IF NOT EXISTS documents (
  id SERIAL PRIMARY KEY, order_id INTEGER REFERENCES orders(id) ON DELETE CASCADE,
  doc_type VARCHAR(32) NOT NULL, storage_key VARCHAR(255) NOT NULL, mime_type VARCHAR(64) NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP);
CREATE TABLE IF NOT EXISTS receipts (
  id SERIAL PRIMARY KEY, order_id INTEGER REFERENCES orders(id) ON DELETE CASCADE,
  receipt_number VARCHAR(32) UNIQUE NOT NULL, buyer_initials VARCHAR(16) NOT NULL,
  amount NUMERIC(12, 2) NOT NULL, created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP);
CREATE TABLE IF NOT EXISTS jobs (
  id SERIAL PRIMARY KEY, order_id INTEGER REFERENCES orders(id) ON DELETE CASCADE,
  job_type VARCHAR(32) NOT NULL, status VARCHAR(32) NOT NULL DEFAULT 'pending',
  attempts INTEGER DEFAULT 0, error_message TEXT, created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP);
